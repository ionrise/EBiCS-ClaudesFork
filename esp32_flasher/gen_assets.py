"""
Generate the data headers of the ESP32-C3 flasher (EBiCS_Flasher/fw_variants.h, EBiCS_Flasher/web_page.h).

    python setup_app/build_variants.py          # firmware variants into android_app/assets/firmware
    python esp32_flasher/gen_assets.py          # embed them + the web page into the ESP32 sketch

fw_variants.h: every prebuilt firmware (display x hall/sensorless) with its CRC-32 and the addresses of the
variables the web page reads (live data, calibration mailbox). web_page.h: web/index.html with
web/settings_block.js inlined, gzip compressed.

Part of EBiCS, GPL v3 or later.
"""
import argparse
import base64
import gzip
import json
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SKETCH = HERE / "EBiCS_Flasher"

SYMS = ["ui32_setup_magic", "ui8_setup_cmd", "ui8_setup_state", "ui8_setup_progress", "ui8_setup_halls_found",
        "ui8_hall_calibrated", "ui32_hall_events", "ui32_pas_events", "brake_flag", "ui16_throttle",
        "ui16_throttle_offset", "uint16_full_rotation_counter", "ui32_KV", "ui8_watchdog_reset",
        "ui16_motor_temp_adc", "ui8_sensorless_running", "ui8_settings_source", "ui8_motor_temp_sensor_ok",
        "MS", "adcData", "Hall_45", "Hall_51", "Hall_13", "Hall_32", "Hall_26", "Hall_64"]


def c_bytes(data, per_line=24):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def gen_variants(fw_dir):
    man = json.loads((fw_dir / "manifest.json").read_text())
    out = ["// generated by esp32_flasher/gen_assets.py - do not edit", "#pragma once", "#include <stdint.h>", "",
           f'static const char FW_VERSION[] = "{man["firmware_version"]}";', "",
           "struct FwSym { const char *name; uint32_t addr; uint16_t size; };",
           "struct FwVariant { const char *name, *display, *label; bool sensorless; const uint8_t *data; uint32_t size;"
           " uint32_t crc; const FwSym *syms; uint8_t nsyms; };", ""]
    entries = []
    for i, v in enumerate(x for x in man["variants"] if not x.get("param_id")):   # no measuring firmware on the ESP32
        data = (fw_dir / v["file"]).read_bytes()
        syms = json.loads((fw_dir / v["symbols"]).read_text())
        out.append(f"static const uint8_t fw_{i}[] = {{\n{c_bytes(data)}\n}};")
        rows = [f'  {{"{n}", {syms[n][0]}u, {syms[n][1]}}},' for n in SYMS if n in syms]
        out.append(f"static const FwSym sym_{i}[] = {{\n" + "\n".join(rows) + "\n};")
        label = v["display_label"].replace('"', "'")
        entries.append(f'  {{"{v["name"]}", "{v["display"]}", "{label}", {str(v["sensorless"]).lower()}, fw_{i}, '
                       f'{len(data)}u, 0x{zlib.crc32(data) & 0xFFFFFFFF:08X}u, sym_{i}, {len(rows)}}},')
    out.append("static const FwVariant FW_VARIANTS[] = {\n" + "\n".join(entries) + "\n};")
    out.append(f"static const int FW_VARIANT_COUNT = {len(entries)};")
    (SKETCH / "fw_variants.h").write_text("\n".join(out) + "\n")
    return len(entries)


def gen_page():
    html = (HERE / "web" / "index.html").read_text(encoding="utf-8")
    js = (HERE / "web" / "settings_block.js").read_text(encoding="utf-8")
    html = html.replace('<script src="settings_block.js"></script>', "<script>\n" + js + "\n</script>")
    html = html.replace("{{LOGO}}", base64.b64encode((HERE / "web" / "logo.png").read_bytes()).decode())
    gz = gzip.compress(html.encode("utf-8"), 9, mtime=0)
    (SKETCH / "web_page.h").write_text("// generated by esp32_flasher/gen_assets.py - do not edit\n#pragma once\n"
                                       f"static const unsigned int WEB_PAGE_GZ_LEN = {len(gz)};\n"
                                       f"static const uint8_t WEB_PAGE_GZ[] = {{\n{c_bytes(gz)}\n}};\n")
    return len(html), len(gz)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--firmware", default=str(REPO / "android_app" / "assets" / "firmware"))
    a = ap.parse_args()
    n = gen_variants(Path(a.firmware))
    raw, gz = gen_page()
    print(f"fw_variants.h: {n} variants, web_page.h: {raw} bytes -> {gz} gzip")
